"use strict";
/* TreadLab JS engine test suite -- open /_test/ in the browser.

   Two halves:
   1. BYTE IDENTITY -- every golden file generated by the Python engine
      (tests/make_golden.py) is rebuilt here from the same request and
      compared byte for byte. This is the real guarantee that moving off
      Python changed nothing about the files you upload.
   2. BEHAVIOUR -- the checks from tests/selfcheck.py that apply to the
      engine itself, so the JS is also tested on its own terms. */

import { buildExport, describeFit, parseFit, writeActivityFit } from "../engine/index.js";
import { crc16, pyRound } from "../engine/fitbase.js";
import { mergeHr } from "../engine/merge.js";
import { addTexture } from "../engine/terrain.js";
import { LOCATIONS, addOceanLoop, ANCHOR_LAT, ANCHOR_LON } from "../engine/gps_loop.js";

const G = "./golden/";
const results = [];
const check = (label, ok, detail = "") => results.push({ label, ok: !!ok, detail });

const getJson = async (p) => (await fetch(p)).json();
const getBytes = async (p) => new Uint8Array(await (await fetch(p)).arrayBuffer());

function cmpBytes(mine, gold) {
  if (mine.length !== gold.length) return `length ${mine.length} vs ${gold.length}`;
  for (let i = 0; i < mine.length; i++) {
    if (mine[i] !== gold[i]) {
      return `first difference at byte ${i}: got ${mine[i]}, expected ${gold[i]}`;
    }
  }
  return null;
}

function hav(a, b, c, d) {
  const p1 = a * Math.PI / 180, p2 = c * Math.PI / 180;
  const dp = p2 - p1, dl = (d - b) * Math.PI / 180;
  const x = Math.sin(dp / 2) ** 2 + Math.cos(p1) * Math.cos(p2) * Math.sin(dl / 2) ** 2;
  return 2 * 6371000 * Math.asin(Math.sqrt(x));
}

export async function runTests() {
  results.length = 0;

  /* ---------------------------------------------- 1. byte identity ---- */
  const names = await getJson(G + "index.json");
  for (const name of names) {
    if (name === "real_sample") continue;
    const meta = await getJson(`${G}${name}.json`);
    const gold = await getBytes(`${G}${name}.fit`);
    let mine, err = null;
    try {
      if (name === "raw_writer") {
        mine = writeActivityFit(meta.records, {
          sport: meta.sport, subSport: meta.sub_sport,
          calories: meta.calories, laps: meta.laps,
        });
      } else {
        const built = buildExport(meta.request);
        mine = built.fit;
        if (built.name !== meta.name) {
          err = `filename ${built.name} vs ${meta.name}`;
        }
        if (!err && meta.merge) {
          const m = built.mergeStats;
          if (!m || m.matched !== meta.merge.matched || m.total !== meta.merge.total
              || m.hr_points !== meta.merge.hr_points) {
            err = `merge stats ${JSON.stringify(m)} vs ${JSON.stringify(meta.merge)}`;
          }
        }
      }
      err = err || cmpBytes(mine, gold);
    } catch (exc) {
      err = "threw: " + exc.message;
    }
    check(`byte-identical to Python: ${name} (${gold.length} B)`, !err, err || "");
  }

  /* ---------------------------------------------- 2. parser vs Python -- */
  if (names.includes("real_sample")) {
    const gold = await getJson(G + "real_sample.json");
    const bytes = await getBytes(G + "real_sample.fit");
    const p = parseFit(bytes);
    check(`real device file: ${p.records.length} records (Python read ${gold.n})`,
          p.records.length === gold.n);
    check("real device file: no spurious warnings",
          JSON.stringify(p.warnings) === JSON.stringify(gold.warnings),
          JSON.stringify(p.warnings));
    let worst = 0, worstCol = "", mismatches = 0;
    for (const [col, want] of Object.entries(gold.cols)) {
      const got = p.records.map((r) => r[col] ?? null);
      for (let i = 0; i < want.length; i++) {
        const a = got[i], b = want[i];
        if (a === null || b === null) {
          if (a !== b) mismatches++;
        } else {
          const d = Math.abs(a - b);
          if (d > worst) { worst = d; worstCol = col; }
        }
      }
    }
    check("real device file: every stream matches Python exactly",
          mismatches === 0 && worst === 0,
          `null mismatches ${mismatches}, worst numeric drift ${worst} (${worstCol})`);
    check("real device file: session + file_id match",
          JSON.stringify(p.session) === JSON.stringify(gold.session)
          && p.fileId.manufacturer === gold.file_id.manufacturer,
          JSON.stringify(p.session));
    const d = describeFit(bytes);
    check("describeFit on a real file returns a usable summary",
          d.ok && d.n_records === gold.n && d.samples.length > 0);
  }

  /* ---------------------------------------------- 3. behaviour -------- */
  check("crc16 known vector '123456789' == 0xBB3D",
        crc16(new TextEncoder().encode("123456789")) === 0xBB3D);
  check("pyRound is half-to-even like Python",
        pyRound(0.5) === 0 && pyRound(1.5) === 2 && pyRound(2.5) === 2
        && pyRound(-0.5) === 0 && pyRound(-1.5) === -2 && pyRound(-2.5) === -2,
        [0.5, 1.5, 2.5, -0.5, -1.5, -2.5].map(pyRound).join(","));

  let recs = Array.from({ length: 101 }, (_, t) => ({ t }));
  const samples = Array.from({ length: 101 }, (_, t) => [t + 0.4, 100 + t, 170.0, 22]);
  let st = mergeHr(recs, samples);
  check("merge: full coverage", st.matched === 101, JSON.stringify(st));
  check("merge: nearest sample wins", recs[50].hr === 150);
  check("merge: cadence + temperature ride along",
        recs[50].cad === 170.0 && recs[50].temp === 22);
  recs = Array.from({ length: 101 }, (_, t) => ({ t }));
  mergeHr(recs, samples, { copyCadence: false, copyTemp: false });
  check("merge: cadence/temperature suppressed when off",
        recs[50].cad === undefined && recs[50].temp === undefined);
  recs = Array.from({ length: 101 }, (_, t) => ({ t }));
  mergeHr(recs, [[0.0, 140, null], [100.0, 160, null]]);
  check("merge: carry-forward capped at 10 s",
        recs[10].hr === 140 && recs[50].hr === undefined);
  recs = Array.from({ length: 101 }, (_, t) => ({ t }));
  mergeHr(recs, samples, { offset: 30 });
  check("merge: +30 s offset shifts the stream", recs[0].hr === 130);
  recs = Array.from({ length: 10 }, (_, t) => ({ t }));
  st = mergeHr(recs, [[3.0, 0, null], [4.0, 300, null]]);
  check("merge: 0 / 300 bpm dropouts ignored", st.matched === 0);
  recs = Array.from({ length: 11 }, (_, t) => ({ t }));
  mergeHr(recs, Array.from({ length: 11 }, (_, t) => [t, 130, 170.0]));
  check("merge: legacy 3-element samples still work",
        recs[5].hr === 130 && recs[5].temp === undefined);

  const flat = Array.from({ length: 1001 }, (_, t) => ({ dist: 3 * t, alt: 42.0 }));
  addTexture(flat);
  check("texture: flat stays perfectly flat", flat.every((r) => r.alt === 42.0));
  const climb = Array.from({ length: 1201 }, (_, t) => ({ dist: 3 * t, alt: 0.09 * t }));
  addTexture(climb);
  check("texture: endpoints pinned (net elevation exact)",
        Math.abs(climb[0].alt) < 1e-9 && Math.abs(climb[1200].alt - 108) < 1e-9);
  check("texture: climb stays strictly monotonic",
        climb.every((r, i) => i === 0 || r.alt > climb[i - 1].alt));
  const dev = Math.max(...climb.map((r, i) => Math.abs(r.alt - 0.09 * i)));
  check("texture: sub-metre undulation present (<= 0.3 m)",
        dev > 0.02 && dev <= 0.30, dev.toFixed(3) + " m");

  for (const [key, [lat0, lon0]] of Object.entries(LOCATIONS)) {
    const loop = Array.from({ length: 4001 }, (_, i) => ({ dist: i * 2.5 }));
    check(`loop ${key}: positions every record`,
          addOceanLoop(loop, lat0, lon0) === 4001);
    const len = loop.reduce((s, r, i) =>
      i ? s + hav(loop[i - 1].lat, loop[i - 1].lon, r.lat, r.lon) : 0, 0);
    check(`loop ${key}: length equals the 10 km distance`,
          Math.abs(len - 10000) < 100, len.toFixed(1) + " m");
    check(`loop ${key}: closes on itself and stays put`,
          hav(loop[0].lat, loop[0].lon, loop[4000].lat, loop[4000].lon) < 1.5
          && Math.max(...loop.map((r) => hav(lat0, lon0, r.lat, r.lon))) < 5000);
  }
  check("loop anchors: watopia is the default",
        LOCATIONS.watopia[0] === ANCHOR_LAT && LOCATIONS.watopia[1] === ANCHOR_LON);

  let threw = false;
  try { parseFit(new TextEncoder().encode("this is not a fit file at all....")); }
  catch (e) { threw = true; }
  check("garbage input throws", threw);
  const good = await getBytes(G + "cam_10k.fit");
  const cut = parseFit(good.subarray(0, 2000));
  check("truncated file -> records + warning, no crash",
        cut.records.length > 0 && cut.warnings.length > 0, cut.warnings[0] || "");
  const chained = new Uint8Array(good.length * 2);
  chained.set(good, 0); chained.set(good, good.length);
  check("chained FIT containers both parse",
        parseFit(chained).blocks === 2);

  const passed = results.filter((r) => r.ok).length;
  return { passed, failed: results.length - passed, results };
}
